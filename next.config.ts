import type { NextConfig } from "next";

/**
 * Cache Components is intentionally OFF. Every screen in Delta Flow is scoped
 * to the signed-in member and their permissions; rendering per request removes
 * any chance of a shared cache serving one member's data to another.
 * See ARCHITECTURE.md › "Rendering & caching".
 */
const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
];

const nextConfig: NextConfig = {
  cacheComponents: false,
  poweredByHeader: false,
  turbopack: {
    rules: {
      "*.css": { loaders: ["@tailwindcss/turbopack"], as: "*.css" },
    },
  },
  experimental: {
    serverActions: { bodySizeLimit: "2mb" }, // files never go through actions: uploads are direct to storage
  },
  async headers() {
    return [
      { source: "/:path*", headers: securityHeaders },
      {
        source: "/aprovacao/:path*",
        headers: [
          { key: "X-Robots-Tag", value: "noindex, nofollow, noarchive" },
          { key: "Cache-Control", value: "private, no-store" },
          { key: "Referrer-Policy", value: "no-referrer" },
        ],
      },
    ];
  },
};

export default nextConfig;
